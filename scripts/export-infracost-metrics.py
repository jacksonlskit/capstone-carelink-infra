#!/usr/bin/env python3
"""Regenerate the FinOps cost metrics that Grafana shows (ADR 0009).

Infracost prices the Terraform in infra/ for both environments (projects in
infracost.yml at the repository root). This script turns that estimate into
Prometheus metrics in observability/finops/01-infracost-metrics-cm.yaml, which
Argo CD serves through the infracost-exporter in each cluster.

Only that ConfigMap is generated. The exporter (02-...) and the dashboard
(03-...) are normal files: edit them by hand.

Usage (from anywhere; paths are relative to the repository):
  scripts/export-infracost-metrics.py           scan, then rewrite the ConfigMap
  scripts/export-infracost-metrics.py --check   scan, then only report whether the
                                                committed ConfigMap is out of date

Prerequisites: Infracost CLI v2.20.0 (`brew install infracost`), logged in with
`infracost auth login`, or INFRACOST_CLI_AUTHENTICATION_TOKEN set (CI).

Re-run it after any change to what Infracost prices (RDS, NAT gateways, the EKS
control plane or node group, KMS, ...), then commit the ConfigMap. The
infracost.yaml workflow runs --check on every infra pull request and warns when
the committed numbers no longer match the code.
"""

import argparse
import difflib
import json
import os
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CONFIGMAP = REPO / "observability" / "finops" / "01-infracost-metrics-cm.yaml"
EKS_TF = REPO / "infra" / "eks.tf"

HEADER = """# Generated by scripts/export-infracost-metrics.py from infracost.yml; do not
# edit by hand. Re-run the script after changing priced Terraform resources.
"""


def infracost(*args: str) -> str:
    """Run the Infracost CLI in the repository root (where infracost.yml is)."""
    return subprocess.run(
        ["infracost", *args], cwd=REPO, check=True, text=True, stdout=subprocess.PIPE
    ).stdout


def priced_node_count() -> int:
    """Infracost prices the node group at its desired_size, so divide by that.

    Reading it from infra/eks.tf keeps the per-node price tied to the code
    instead of to whichever cluster the local kubectl happens to point at.
    """
    match = re.search(r"desired_size\s*=\s*(\d+)", EKS_TF.read_text())
    if not match:
        sys.exit(f"could not find desired_size in {EKS_TF}")
    return int(match.group(1))


def classify_service(resource: str) -> str:
    if "aws_db_instance" in resource and "mysql" in resource:
        return "rds_mysql"
    if "aws_db_instance" in resource and "postgres" in resource:
        return "rds_postgres"
    if "aws_eks_node_group" in resource:
        return "eks_compute"
    if "aws_eks_cluster" in resource:
        return "eks_control_plane"
    if "aws_nat_gateway" in resource:
        return "nat_gateway"
    # Everything else Infracost prices: KMS keys, Secrets Manager, CloudWatch,
    # the Discord Lambda, ... The label name is kept for the existing dashboard.
    return "observability_kms_secrets"


def build_configmap() -> str:
    infracost("scan")
    items = json.loads(
        infracost("inspect", "--costs-only", "--group-by", "project,resource", "--json")
    )
    nodes = priced_node_count()

    baseline = defaultdict(float)  # (environment, service) -> monthly USD
    node_group = defaultdict(float)  # environment -> monthly USD for all nodes
    for item in items:
        cols = item.get("columns", {})
        env = cols.get("project", "unknown").replace("carelink-", "")
        resource = cols.get("resource", "")
        cost = float(item.get("cost", 0))
        if cost <= 0:
            continue
        service = classify_service(resource)
        baseline[(env, service)] += cost
        if service == "eks_compute":
            node_group[env] += cost

    lines = [
        "# HELP carelink_infracost_baseline_monthly_usd Baseline monthly AWS cost from Terraform IaC (USD)",
        "# TYPE carelink_infracost_baseline_monthly_usd gauge",
    ]
    for (env, service), cost in sorted(baseline.items()):
        lines.append(
            f'carelink_infracost_baseline_monthly_usd{{environment="{env}",service="{service}"}} {cost:.4f}'
        )
    lines += [
        "# HELP carelink_infracost_fixed_monthly_usd Non-EC2 fixed monthly AWS cost from Terraform IaC (USD)",
        "# TYPE carelink_infracost_fixed_monthly_usd gauge",
    ]
    for (env, service), cost in sorted(baseline.items()):
        if service != "eks_compute":
            lines.append(
                f'carelink_infracost_fixed_monthly_usd{{environment="{env}",service="{service}"}} {cost:.4f}'
            )
    lines += [
        "# HELP carelink_infracost_ec2_node_unit_monthly_usd Monthly AWS cost per EKS EC2 worker node (USD)",
        "# TYPE carelink_infracost_ec2_node_unit_monthly_usd gauge",
    ]
    for env, cost in sorted(node_group.items()):
        lines.append(
            f'carelink_infracost_ec2_node_unit_monthly_usd{{environment="{env}"}} {cost / nodes:.4f}'
        )

    metrics = "\n".join("    " + line for line in lines)
    return (
        HEADER
        + "apiVersion: v1\n"
        + "kind: ConfigMap\n"
        + "metadata:\n"
        + "  name: infracost-metrics\n"
        + "  namespace: monitoring\n"
        + "data:\n"
        + "  metrics: |\n"
        + metrics
        + "\n"
    )


def check(generated: str) -> None:
    """Report drift without failing: prices can change on AWS's side too."""
    committed = CONFIGMAP.read_text() if CONFIGMAP.exists() else ""
    rel = CONFIGMAP.relative_to(REPO)
    if committed == generated:
        print(f"{rel} matches the current Terraform.")
        return

    diff = "".join(
        difflib.unified_diff(
            committed.splitlines(keepends=True),
            generated.splitlines(keepends=True),
            fromfile=f"{rel} (committed)",
            tofile=f"{rel} (from current Terraform)",
        )
    )
    print(diff)
    message = (
        f"{rel} is out of date. Run scripts/export-infracost-metrics.py "
        "and commit the result."
    )
    if os.environ.get("GITHUB_ACTIONS") == "true":
        print(f"::warning file={rel}::{message}")
        summary = os.environ.get("GITHUB_STEP_SUMMARY")
        if summary:
            with open(summary, "a") as f:
                f.write(f"### FinOps metrics drift\n\n{message}\n\n```diff\n{diff}```\n")
    else:
        print(message)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="only report whether the committed ConfigMap is out of date",
    )
    args = parser.parse_args()

    generated = build_configmap()
    if args.check:
        check(generated)
    else:
        CONFIGMAP.write_text(generated)
        print(f"Wrote {CONFIGMAP.relative_to(REPO)} ({priced_node_count()} nodes priced per environment)")


if __name__ == "__main__":
    main()
